// Synchronize explicit image declarations with application references.
import {readFileSync, writeFileSync, readdirSync, statSync} from 'node:fs';
import {basename, dirname, join, relative, resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const defaultRoot = fileURLToPath(new URL('../', import.meta.url));
const begin = '    # BEGIN REQUIRED IMAGE ASSETS';
const end = '    # END REQUIRED IMAGE ASSETS';

export function requiredImageAssets(source) {
  const paths = new Set();
  for (const match of source.matchAll(/(['"])(assets\/images\/(?:\\.|[^\\\r\n])*?)\1/g)) {
    if (/(?<!\\)\$/.test(match[2])) {
      throw Error('Dynamic image paths need explicit asset declarations.');
    }
    const path = match[2].replace(/\\(['"\\$])/g, '$1');
    if (path.split('/').includes('..')) throw Error(`Invalid image path: ${path}`);
    paths.add(path);
  }
  if (!paths.size) throw Error('No application image paths found; no files changed.');
  return [...paths].sort();
}

export function renderFlutterAssets(pubspec, paths) {
  const newline = pubspec.includes('\r\n') ? '\r\n' : '\n';
  const block = [begin,
    '    # Generated by node tools/sync_flutter_assets.mjs.',
    '    # Only referenced images are bundled; synchronization does not delete files.',
    ...[...new Set(paths)].sort().map(path => `    - ${JSON.stringify(path)}`),
    end,
  ].join(newline);
  const start = pubspec.indexOf(begin), finish = pubspec.indexOf(end);
  if (start !== -1 || finish !== -1) {
    if (start < 0 || finish < start || pubspec.indexOf(begin, start + 1) !== -1 || pubspec.indexOf(end, finish + 1) !== -1) {
      throw Error('Expected one matching pair of required-image markers; no files changed.');
    }
    return pubspec.slice(0, start) + block + pubspec.slice(finish + end.length);
  }
  const broad = /^    - assets\/images\/(?=\r?$)/gm;
  const matches = [...pubspec.matchAll(broad)];
  if (matches.length !== 1) throw Error('Expected the original assets/images/ declaration; no files changed.');
  const match = matches[0];
  return pubspec.slice(0, match.index) + block + pubspec.slice(match.index + match[0].length);
}

function filesUnder(directory) {
  return readdirSync(directory, {withFileTypes: true}).flatMap(entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? filesUnder(path) : [path];
  });
}

export function syncFlutterAssets({projectRoot = defaultRoot, check = false} = {}) {
  const sources = filesUnder(join(projectRoot, 'lib')).filter(path => path.endsWith('.dart'));
  const assets = requiredImageAssets(sources.map(path => readFileSync(path, 'utf8')).join('\n'));
  for (const asset of assets) {
    const file = resolve(projectRoot, asset);
    let valid = false;
    try {
      valid = readdirSync(dirname(file)).includes(basename(file)) && statSync(file).isFile();
    } catch { /* Report missing assets before changing the manifest. */ }
    if (!valid) throw Error(`Missing image or filename case mismatch: ${asset}. No files changed.`);
  }
  const file = join(projectRoot, 'pubspec.yaml');
  const before = readFileSync(file, 'utf8');
  const after = renderFlutterAssets(before, assets);
  if (/^    - ['"]?assets\/images\/['"]?\s*$/m.test(after)) {
    throw Error('A directory-wide image declaration would include unused originals.');
  }
  if (check && before !== after) throw Error('Image asset declarations are out of date. Run node tools/sync_flutter_assets.mjs.');
  if (!check && before !== after) writeFileSync(file, after);
  const originals = filesUnder(join(projectRoot, 'assets/images'));
  const required = new Set(assets);
  const excluded = originals.filter(path => !required.has(relative(projectRoot, path).replaceAll('\\', '/')));
  return {bundled: assets.length, excluded: excluded.length, excludedBytes: excluded.reduce((total, path) => total + statSync(path).size, 0), changed: before !== after};
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    const result = syncFlutterAssets({check: process.argv.includes('--check')});
    console.log(`Bundled images: ${result.bundled}. Excluded originals: ${result.excluded} (${result.excludedBytes} bytes).`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
